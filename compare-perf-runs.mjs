import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

// Diffs two runs recorded in results/mgscan-perf-trend.json, label-by-label, and
// writes a markdown comparison to stdout (redirect to a docs/ file to save it).
// Defaults to the two most recent runs so "compare the latest release against
// whatever came before it" needs no arguments in the common case.
//
// Usage:
//   node compare-perf-runs.mjs                    (last two runs)
//   node compare-perf-runs.mjs <runStampA> <runStampB>

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const trendPath = path.join(__dirname, 'results', 'mgscan-perf-trend.json');

const THRESHOLDS = {
  'Action -': { good: 1000, ok: 3000 },
  'Page Load': { good: 2000, ok: 4000 },
  'Login': { good: 3000, ok: 6000 },
  'Post-login': { good: 2000, ok: 4000 },
};
function verdictFor(label, ms) {
  const bucketKey = Object.keys(THRESHOLDS).find(k => label.startsWith(k)) || 'Page Load';
  const t = THRESHOLDS[bucketKey];
  if (ms <= t.good) return 'Good';
  if (ms <= t.ok) return 'Acceptable';
  return 'Slow';
}

if (!fs.existsSync(trendPath)) {
  console.error(`No trend log found at ${trendPath} - run record-perf-run.mjs at least twice first.`);
  process.exit(1);
}
const trend = JSON.parse(fs.readFileSync(trendPath, 'utf-8'));
if (trend.runs.length < 2) {
  console.error(`Trend log only has ${trend.runs.length} run(s) - need at least 2 to compare.`);
  process.exit(1);
}

const [, , argA, argB] = process.argv;
const runA = argA ? trend.runs.find(r => r.runStamp === argA) : trend.runs[trend.runs.length - 2];
const runB = argB ? trend.runs.find(r => r.runStamp === argB) : trend.runs[trend.runs.length - 1];
if (!runA || !runB) {
  console.error('Could not find one or both requested runStamps in the trend log.');
  console.error('Available:', trend.runs.map(r => r.runStamp).join(', '));
  process.exit(1);
}

// Normalizes pre-2026-08-12 org-hierarchy role labels ('employee'/'manager') recorded before
// runs switched to the feature's own terms ('Manager'/'Director') so older and newer runs can
// still be diffed step-by-step instead of every renamed step showing as REMOVED+NEW. The
// org-rollup 'director' account has no counterpart in the new scheme (dropped from reporting
// entirely 2026-08-12) and is left unmapped on purpose - its steps correctly show as REMOVED
// when compared against a run that no longer includes that role.
const LEGACY_ROLE_ALIAS = { employee: 'Manager', manager: 'Director' };
function keyOf(s) { return `${LEGACY_ROLE_ALIAS[s.role] || s.role}::${s.label}`; }
const mapA = new Map(runA.steps.map(s => [keyOf(s), s]));
const mapB = new Map(runB.steps.map(s => [keyOf(s), s]));
const allKeys = [...new Set([...mapA.keys(), ...mapB.keys()])];

const releaseKey = (r) => r.release?.confirmedSha || r.release?.releaseId || null;
const sameRelease = releaseKey(runA) !== null && releaseKey(runA) === releaseKey(runB);
if (releaseKey(runA) === null || releaseKey(runB) === null) {
  console.error(`WARNING: one or both runs has no releaseId/confirmedSha set - "same release" detection is disabled for this comparison. Fill in release.releaseId when recording future runs.`);
}

let out = '';
out += `# Management Scan Performance — ${runA.date} (${runA.runStamp}) vs. ${runB.date} (${runB.runStamp})\n\n`;
out += `Auto-generated by \`compare-perf-runs.mjs\`. Trend log: \`results/mgscan-perf-trend.json\`.\n\n`;
out += `## Release identity\n\n`;
out += `- **${runA.date}**: ${runA.release?.confirmedSha ? `confirmed \`${runA.release.confirmedSha}\`` : `approx. \`${runA.release?.approxSha || 'unknown'}\``}${runA.release?.confirmedBy ? ` (confirmed by: ${runA.release.confirmedBy})` : ''}\n`;
out += `- **${runB.date}**: ${runB.release?.confirmedSha ? `confirmed \`${runB.release.confirmedSha}\`` : `approx. \`${runB.release?.approxSha || 'unknown'}\``}${runB.release?.confirmedBy ? ` (confirmed by: ${runB.release.confirmedBy})` : ''}\n`;
if (sameRelease) {
  out += `\n**⚠ Same effective release on both dates** — this comparison is a stability check, not a release-to-release comparison. Timing deltas below reflect environment/session variance, not code changes.\n`;
}
out += `\n## Timing deltas\n\n`;
out += `| Role | Step | ${runA.date} ms | ${runB.date} ms | Δ ms | Δ % | ${runB.date} verdict | Flag |\n`;
out += `|---|---|---:|---:|---:|---:|---|---|\n`;

let regressions = 0;
for (const key of allKeys.sort()) {
  const a = mapA.get(key);
  const b = mapB.get(key);
  const [role, label] = key.split('::');
  if (!a) { out += `| ${role} | ${label} | — | ${b.ms} | — | — | ${verdictFor(label, b.ms)} | NEW STEP |\n`; continue; }
  if (!b) { out += `| ${role} | ${label} | ${a.ms} | — | — | — | — | REMOVED STEP |\n`; continue; }
  const delta = b.ms - a.ms;
  const pct = a.ms > 0 ? ((delta / a.ms) * 100).toFixed(0) : 'n/a';
  const verdictA = verdictFor(label, a.ms);
  const verdictB = verdictFor(label, b.ms);
  const rank = { Good: 0, Acceptable: 1, Slow: 2 };
  let flag = '';
  if (!a.ok || !b.ok) flag = a.ok !== b.ok ? '**OK-STATUS CHANGED**' : '(both failed)';
  else if (rank[verdictB] > rank[verdictA]) { flag = '**REGRESSION**'; regressions++; }
  else if (rank[verdictB] < rank[verdictA]) flag = 'improved';
  out += `| ${role} | ${label} | ${a.ms} | ${b.ms} | ${delta >= 0 ? '+' : ''}${delta} | ${pct}% | ${verdictB} | ${flag} |\n`;
}

out += `\n## Summary\n\n`;
out += regressions > 0
  ? `**${regressions} step(s) regressed** (moved to a worse verdict bucket) — see rows flagged REGRESSION above.\n`
  : `No step regressed to a worse verdict bucket between these two runs.\n`;

console.log(out);
